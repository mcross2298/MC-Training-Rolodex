// Install — cache everything
self.addEventListener('install', event => {
    event.waitUntil(
        caches.open(CACHE_NAME).then(cache => {
            console.log('[SW] Caching', CACHE_URLS.length, 'files');
            // Cache in batches to avoid timeout
            const batch = (arr, size) => Array.from({length:Math.ceil(arr.length/size)}, (_,i) => arr.slice(i*size,i*size+size));
            const batches = batch(CACHE_URLS, 20);
            return batches.reduce((p, b) => p.then(() =>
                Promise.allSettled(b.map(u => cache.add(u).catch(err => console.log('[SW] Cache miss:', u, err))))
            ), Promise.resolve());
        })
    );
    // NOTE: intentionally NOT calling self.skipWaiting() here. Activation is
    // page-controlled (mc-sw-update.js posts 'skipWaiting' only when no workout
    // is in progress) so a new build never force-reloads someone mid-set.
});

// Activate — remove old APP caches and take control (but not FONT_CACHE_NAME,
// which deliberately outlives any one deploy — see its declaration above).
// The page-side reload is driven by mc-sw-update.js's 'controllerchange'
// handler (which guards against reloading mid-workout), so we do NOT
// force-navigate tabs here.
self.addEventListener('activate', event => {
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(
                keys.filter(k => k !== CACHE_NAME && k !== FONT_CACHE_NAME).map(k => {
                    console.log('[SW] Removing old cache:', k);
                    return caches.delete(k);
                })
            ))
            .then(() => self.clients.claim())
    );
});

// Offline fallback page (audit DG-7). Both variants share one themed shell:
// the ONE screen a trainee sees at the worst possible moment — mid-workout,
// signal just dropped — used to be hardcoded dark hex with no light variant
// and system-font text, the least-designed screen in an app that otherwise
// ships a real token system (base.css) and a governed light mode
// (mc-light.css). This mirrors both rather than inventing a third palette,
// and resolves theme with the SAME snippet index.html's own <head> boot
// script uses (mc_theme_mode, falling back to prefers-color-scheme) — a
// Response body renders as a real page once the browser paints it, so this
// inline <script> runs exactly like any other page's before-first-paint
// theme guard, even though the SW itself can't touch localStorage.
//
// Deliberately NOT 'Bebas Neue' for the wordmark (audit DG-1): that face is
// referenced in base.css's athletic theme but loaded nowhere in the app, so
