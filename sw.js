// Install — cache everything
self.addEventListener('install', event => {
    event.waitUntil(
        caches.open(CACHE_NAME).then(cache => {
            console.log('[SW] Caching', CACHE_URLS.length, 'files');
            // Cache in batches to avoid timeout
            const batch = (arr, size) => Array.from({length:Math.ceil(arr.length/size)}, (_,i) => arr.slice(i*size,i*size+size));
            const batches = batch(CACHE_URLS, 20);
            return batches.reduce((p, b) => p.then(() =>
                Promise.allSettled(b.map(u => cache.add(u).catch(err => console.log('[SW] Cache miss:', u, err))))
            ), Promise.resolve());
        })
    );
    // NOTE: intentionally NOT calling self.skipWaiting() here. Activation is
    // page-controlled (mc-sw-update.js posts 'skipWaiting' only when no workout
    // is in progress) so a new build never force-reloads someone mid-set.
});

// Activate — remove old APP caches and take control (but not FONT_CACHE_NAME,
// which deliberately outlives any one deploy — see its declaration above).
// The page-side reload is driven by mc-sw-update.js's 'controllerchange'
// handler (which guards against reloading mid-workout), so we do NOT
// force-navigate tabs here.
//
// R3 / D-17: purging used to delete everything the old deploy had cached,
// including every program page mc-offline-prefetch.js fetched, while its
// "Available offline ✓" record lived on for 14 days. So an update that landed
// on the couch left the athlete with no program at the gym. Before an old
// cache is deleted, whatever the new one does not already hold is moved into
// CARRY_CACHE_NAME (a newer old cache is copied last, so it wins).
//
// Phase T1.4: the carry-over cache used to only grow. Every activate now drops
// a carried copy this deploy's cache holds (it can never be served, since
// CACHE_NAME answers first) and one fetched more than CARRY_MAX_AGE_MS ago by
// its Date header. A page opened online is refetched into CACHE_NAME and
// carried again, fresh, by the next deploy, so only pages nobody has opened
// for two months age out.
//
// Phase T3: a copy with no Date header used to be kept forever, its age
// unknown. The first prune that meets one now stamps it with CARRY_STAMP, so
// it ages from then and goes 60 days later like any other.
const CARRY_MAX_AGE_MS = 60 * 24 * 60 * 60 * 1000;
const CARRY_STAMP = 'x-mc-carried-at';
function carriedAt(resp) {
    const h = resp && resp.headers && resp.headers.get ? resp.headers : null;
    if (!h) return 0;
    return Date.parse(h.get('date') || '') || Number(h.get(CARRY_STAMP)) || 0;
}
function stampCarry(resp, now) {
    try {
        const headers = new Headers(resp.headers);
        headers.set(CARRY_STAMP, String(now));
        return new Response(resp.body, { status: resp.status, statusText: resp.statusText, headers });
    } catch (e) { return null; }
}
function pruneCarry(fresh, carry, now) {
    if (!carry.delete) return Promise.resolve();
    return carry.keys().then(reqs => Promise.all(reqs.map(req =>
        fresh.match(req).then(hit => {
            if (hit) return carry.delete(req);
            return carry.match(req).then(resp => {
                if (!resp) return null;
                const d = carriedAt(resp);
                if (d) return (now - d > CARRY_MAX_AGE_MS) ? carry.delete(req) : null;
                const stamped = stampCarry(resp, now);
                return stamped ? carry.put(req, stamped) : null;
            });
        }).catch(() => null))));
}
function retireOldCaches(keys) {
    const old = keys.filter(k => k !== CACHE_NAME && k !== FONT_CACHE_NAME && k !== CARRY_CACHE_NAME)
        // numeric order, so v99 sorts before v183 and the newest copy is written last
        .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    if (!old.length && keys.indexOf(CARRY_CACHE_NAME) < 0) return Promise.resolve();
    return Promise.all([caches.open(CACHE_NAME), caches.open(CARRY_CACHE_NAME)]).then(([fresh, carry]) =>
        old.reduce((p, k) => p.then(() => caches.open(k).then(oc => oc.keys().then(reqs =>
            Promise.all(reqs.map(req => fresh.match(req).then(hit => hit ? null :
                oc.match(req).then(resp => resp ? carry.put(req, resp) : null)).catch(() => null)))
        )).then(() => {
            console.log('[SW] Removing old cache:', k);
            return caches.delete(k);
        })), Promise.resolve())
        .then(() => pruneCarry(fresh, carry, Date.now()))
    );
}
self.addEventListener('activate', event => {
    event.waitUntil(
        caches.keys()
            .then(retireOldCaches)
            .catch(() => {})
            .then(() => self.clients.claim())
    );
});

